/** Багшилж эхэлсэн он — "хэдэн дэх жилдээ" гэдгийг үүнээс тоолно. */
export const BATCHIMEG_START_YEAR = 1991;

/** 2026 онд 35 дахь жил. Хуудсанд хатуу бичихгүй, жил бүр өөрөө нэмэгдэнэ. */
export function batchimegTeachingYear(now = new Date()): number {
  return now.getUTCFullYear() - BATCHIMEG_START_YEAR;
}

